"""Write circuits/afe_eval_stair.cir: afe_eval.cir with V_EXC replaced by a NUCLEO-DAC staircase (P-26b).

The staircase has N samples per period (default 128), 12-bit codes on a 3.3 V full scale, and holds each sample
for 1/(N f0) (zero-order hold). Run from the ti-pspice folder: python circuits/gen_exc_stair.py [--periods 60] [--n 128] [--bits 12] [--out name.cir]
"""
import argparse
import math
import re
from pathlib import Path

ap = argparse.ArgumentParser()
ap.add_argument("--f0", type=float, default=518.0)
ap.add_argument("--n", type=int, default=128)
ap.add_argument("--bits", type=int, default=12)
ap.add_argument("--vfs", type=float, default=3.3)
ap.add_argument("--dc", type=float, default=1.65)
ap.add_argument("--amp", type=float, default=0.3)
ap.add_argument("--periods", type=int, default=60)
ap.add_argument("--edge", type=float, default=100e-9, help="DAC step transition time")
ap.add_argument("--out", default="afe_eval_stair.cir", help="output file name in circuits/")
a = ap.parse_args()

here = Path(__file__).resolve().parent
src = (here / "afe_eval.cir").read_text()
lsb = a.vfs / 2**a.bits
ts = 1 / (a.f0 * a.n)
pts = []
for k in range(a.periods * a.n):
    v = round((a.dc + a.amp * math.sin(2 * math.pi * k / a.n)) / lsb) * lsb
    t = k * ts
    if k:
        pts.append(f"+ {t + a.edge:.9e} {v:.6f}")
    else:
        pts.append(f"+ 0 {v:.6f}")
    pts.append(f"+ {t + ts:.9e} {v:.6f}")
stair = "V_EXC        EXC_DAC 0 PWL\n" + "\n".join(pts)
out, n = re.subn(r"^V_EXC .*$", lambda m: stair, src, count=1, flags=re.M)
assert n == 1
out = out.replace("* afe_eval.cir:", f"* {a.out} (generated by gen_exc_stair.py: {a.n} samples/period, {a.bits} bit, "
                  f"{a.periods} periods). Base:\n* afe_eval.cir:", 1)
(here / a.out).write_text(out)
print(f"wrote {a.out}, {len(pts)} PWL points, LSB {lsb*1e3:.4f} mV, sample {ts*1e6:.3f} us")
